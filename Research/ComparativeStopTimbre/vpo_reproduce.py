"""Acquire and verify the exact VPO bytes used by the comparative study.

The lock generated by this program deliberately defines equivalence at the
analysis-input boundary: every selected GrandOrgue definition and every unique
audio file that contributed an observation must be present with its frozen
SHA-256. It does not claim byte equivalence for files that were never analyzed
or for the former 591 GB discovery collection as a whole.
"""

