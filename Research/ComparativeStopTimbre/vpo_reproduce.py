def canonical_csv(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        return {"fieldnames": reader.fieldnames, "rows": list(reader)}


def compare_results(reference_dir: Path, candidate_dir: Path) -> dict[str, Any]:
    files = []
    for filename in RESULT_JSON_FILES + RESULT_CSV_FILES:
        reference_path = reference_dir / filename
        candidate_path = candidate_dir / filename
        if not reference_path.is_file() or not candidate_path.is_file():
            files.append({
                "file": filename,
                "equivalent": False,
                "error": "missing reference or candidate file",
            })
            continue
        if filename.endswith(".json"):
            reference = load_json(reference_path)
            candidate = load_json(candidate_path)
        else:
            reference = canonical_csv(reference_path)
            candidate = canonical_csv(candidate_path)
        files.append({
            "file": filename,
            "equivalent": reference == candidate,
            "referenceCanonicalSHA256": canonical_json_hash(reference),
            "candidateCanonicalSHA256": canonical_json_hash(candidate),
        })
    equivalent = all(item["equivalent"] for item in files)
    return {
        "contractVersion": RESULT_COMPARISON_CONTRACT,
        "generatedAt": utc_now(),
        "status": "scientific results equivalent" if equivalent else "result variant",
        "equivalent": equivalent,
        "comparisonBoundary": "Exact canonical comparison of the statistical summary and all analysis CSV tables; run-provenance timestamps/paths and renderer-dependent figures are excluded.",
        "reference": str(reference_dir.resolve()),
        "candidate": str(candidate_dir.resolve()),
        "files": files,
    }


