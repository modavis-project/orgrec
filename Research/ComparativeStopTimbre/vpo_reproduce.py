class ReproductionError(RuntimeError):
    pass


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def sha256_file(path: Path, chunk_size: int = 8 * 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(chunk_size):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_stream(handle: Any, chunk_size: int = 8 * 1024 * 1024) -> str:
    digest = hashlib.sha256()
    while chunk := handle.read(chunk_size):
        digest.update(chunk)
    return digest.hexdigest()


def canonical_json_hash(value: Any) -> str:
    payload = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def load_json(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        json.dump(value, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")
    os.replace(temporary, path)


def parse_root_maps(values: list[str]) -> list[tuple[str, str]]:
    mappings: list[tuple[str, str]] = []
    for value in values:
        if "=" not in value:
            raise ReproductionError(f"Invalid --root-map value: {value}")
        old, new = value.split("=", 1)
        old = old.rstrip("/")
        new = new.rstrip("/")
        if not old or not new:
            raise ReproductionError(f"Invalid --root-map value: {value}")
        mappings.append((old, new))
    old_roots = [old for old, _ in mappings]
    if len(set(old_roots)) != len(old_roots):
        raise ReproductionError("Duplicate old root in --root-map values")
    return sorted(mappings, key=lambda item: len(item[0]), reverse=True)


def remap_path(value: str, mappings: list[tuple[str, str]]) -> tuple[str, bool]:
    for old, new in mappings:
        if value == old or value.startswith(old + "/"):
            return new + value[len(old):], True
    return value, False


def remap_inventory(
    inventory_path: Path,
    output_path: Path,
    mappings: list[tuple[str, str]],
) -> dict[str, Any]:
    with inventory_path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        fieldnames = reader.fieldnames
        if not fieldnames or "path" not in fieldnames:
            raise ReproductionError("Inventory has no path column")
        rows = list(reader)
    remapped_rows = 0
    mapped_missing: list[dict[str, str]] = []
    current_existing = 0
    for row in rows:
        was_expected_present = row.get("path_exists", "").lower() == "yes"
        new_path, changed = remap_path(row.get("path", ""), mappings)
        row["path"] = new_path
        if changed:
            remapped_rows += 1
        exists = bool(new_path) and Path(new_path).exists()
        if "path_exists" in row:
            row["path_exists"] = "yes" if exists else "no"
        if exists:
            current_existing += 1
        elif changed and was_expected_present:
            mapped_missing.append({"entityID": row.get("entity_id", ""), "path": new_path})
        if "manifest_path" in row:
            row["manifest_path"], _ = remap_path(row.get("manifest_path", ""), mappings)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = output_path.with_name(output_path.name + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    os.replace(temporary, output_path)
    return {
        "contractVersion": INVENTORY_REMAP_CONTRACT,
        "generatedAt": utc_now(),
        "sourceInventory": str(inventory_path.resolve()),
        "sourceInventorySHA256": sha256_file(inventory_path),
        "outputInventory": str(output_path.resolve()),
        "outputInventorySHA256": sha256_file(output_path),
        "rootMappings": [{"old": old, "new": new} for old, new in mappings],
        "summary": {
            "rowCount": len(rows),
            "remappedRowCount": remapped_rows,
            "currentExistingPathCount": current_existing,
            "historicallyExpectedPresentMissingPathCount": len(mapped_missing),
        },
        "historicallyExpectedPresentMissingPaths": mapped_missing,
    }


def scientific_corpus_payload(document: dict[str, Any]) -> dict[str, Any]:
    """Return the scientific payload, excluding machine/run provenance paths."""
    instruments = []
    for source in document.get("instruments", []):
        item = dict(source)
        item.pop("sourceDefinitionPath", None)
        instruments.append(item)
    ranks = json.loads(json.dumps(document.get("ranks", [])))
    for rank in ranks:
        for observation in rank.get("observations", []):
            observation.pop("id", None)
    return {
        "contractVersion": document.get("contractVersion"),
        "sourceMutationPolicy": document.get("sourceMutationPolicy"),
        "options": document.get("options"),
        "catalogSHA256": document.get("catalogSHA256"),
        "instruments": instruments,
        "ranks": ranks,
        "exclusions": document.get("exclusions", []),
        "warnings": document.get("warnings", []),
    }


def compare_corpora(reference_path: Path, candidate_path: Path) -> dict[str, Any]:
    reference = scientific_corpus_payload(load_json(reference_path))
    candidate = scientific_corpus_payload(load_json(candidate_path))
    sections = {}
    for key in reference:
        sections[key] = {
            "equivalent": reference.get(key) == candidate.get(key),
            "referenceSHA256": canonical_json_hash(reference.get(key)),
            "candidateSHA256": canonical_json_hash(candidate.get(key)),
        }
    equivalent = reference == candidate
    return {
        "contractVersion": CORPUS_COMPARISON_CONTRACT,
        "generatedAt": utc_now(),
        "status": "feature-corpus equivalent" if equivalent else "corpus variant",
        "equivalent": equivalent,
        "comparisonBoundary": "Scientific corpus content; generated time, software build metadata, inventory path/hash, catalog path, source-definition filesystem paths, and randomly generated observation record UUIDs are excluded.",
        "reference": str(reference_path.resolve()),
        "candidate": str(candidate_path.resolve()),
        "referencePayloadSHA256": canonical_json_hash(reference),
        "candidatePayloadSHA256": canonical_json_hash(candidate),
        "sections": sections,
    }


