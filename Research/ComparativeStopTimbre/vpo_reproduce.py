def parse_entity_roots(values: list[str]) -> dict[str, Path]:
    result: dict[str, Path] = {}
    for value in values:
        if "=" not in value:
            raise ReproductionError(f"Invalid --entity-root value: {value}")
        entity_id, raw_path = value.split("=", 1)
        entity_id = entity_id.strip()
        if not entity_id or not raw_path:
            raise ReproductionError(f"Invalid --entity-root value: {value}")
        if entity_id in result:
            raise ReproductionError(f"Duplicate --entity-root for {entity_id}")
        result[entity_id] = Path(raw_path)
    return result


def main(argv: list[str] | None = None) -> int:
    arguments = parser().parse_args(argv)
    try:
        if arguments.command == "lock":
            document = build_lock(arguments.corpus, arguments.inventory, arguments.catalog, arguments.routes)
            write_json(arguments.output, document)
            print(json.dumps({"output": str(arguments.output), "sha256": sha256_file(arguments.output), "counts": document["counts"]}, indent=2))
            return 0
        if arguments.command == "remap-inventory":
            report = remap_inventory(arguments.inventory, arguments.output, parse_root_maps(arguments.root_map))
            if arguments.report:
                write_json(arguments.report, report)
            print(json.dumps({"output": str(arguments.output), "summary": report["summary"]}, indent=2))
            return 0 if report["summary"]["historicallyExpectedPresentMissingPathCount"] == 0 else 2
        if arguments.command == "compare-corpus":
            report = compare_corpora(arguments.reference, arguments.candidate)
            write_json(arguments.report, report)
            print(json.dumps({"status": report["status"], "report": str(arguments.report)}, indent=2))
            return 0 if report["equivalent"] else 2
        if arguments.command == "compare-results":
            report = compare_results(arguments.reference, arguments.candidate)
            write_json(arguments.report, report)
            print(json.dumps({"status": report["status"], "report": str(arguments.report)}, indent=2))
            return 0 if report["equivalent"] else 2
        if arguments.command == "reproduce-backup":
            report = reproduce_from_backup(arguments)
            print(json.dumps(report, indent=2))
            return 0 if report["status"] == "exact scientific reproduction" else 2
        lock = load_json(arguments.lock)
        if lock.get("contractVersion") != LOCK_CONTRACT:
            raise ReproductionError("Unsupported acquisition lock contract")
        if arguments.command == "audit":
            report = audit_routes(lock, arguments.timeout)
            if arguments.report:
                write_json(arguments.report, report)
            print_audit(report)
            return 0 if report["summary"]["allRoutesAvailable"] else 2
        if arguments.command == "download":
            if not arguments.accept_source_terms:
                raise ReproductionError(
                    "Downloading requires --accept-source-terms after reviewing current licences and access terms"
                )
            report = download_entities(
                lock,
                arguments.destination,
                arguments.entities,
                not arguments.no_extract,
                arguments.timeout,
            )
            print(json.dumps({"destination": report["destination"], "recordCount": len(report["records"])}, indent=2))
            return 0
        if arguments.command == "verify":
            overrides = parse_entity_roots(arguments.entity_root)
            known = {entity["entityID"] for entity in lock["entities"]}
            unknown = sorted(set(overrides) - known)
            if unknown:
                raise ReproductionError(f"Unknown entity-root IDs: {', '.join(unknown)}")
            report = verify_acquisition(lock, arguments.destination, overrides)
            output = arguments.report or arguments.destination / "verification-report.json"
            write_json(output, report)
            print(json.dumps({"status": report["status"], "summary": report["summary"], "report": str(output)}, indent=2))
            return 0 if report["equivalent"] else 2
        raise ReproductionError(f"Unknown command: {arguments.command}")
    except (ReproductionError, OSError, ValueError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
